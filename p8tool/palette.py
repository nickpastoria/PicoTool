_EXACT = {rgb: i for i, rgb in enumerate(PALETTE)}


def index_of(rgb):
    """Exact palette lookup, or None."""
    return _EXACT.get(tuple(rgb))


def nearest(rgb):
    """Closest palette index by squared RGB distance."""
    r, g, b = rgb
    best, best_d = 0, None
    for i, (pr, pg, pb) in enumerate(PALETTE):
        d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
        if best_d is None or d < best_d:
            best, best_d = i, d
    return best
